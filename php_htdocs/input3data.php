<?php
// =========================================================================
// 1. 【核心邏輯與資料處理區】（放最前面）
//    核心觀念：在 HTML 畫面渲染前，先在這裡把大腦想做的事情（接資料、過濾、比對）處理完。
// =========================================================================

/**
 * 接收並檢查從網址（URL）傳過來的 phone[] 參數。
 * - isset($_GET["phone"])：檢查網址上有沒有 phone 這個參數。
 * - ? $_GET["phone"]     ：有的話，就把這個陣列資料存進 $phone 變數。
 * - : []                 ：沒有的話，就給它一個空陣列 []，防止後面跑迴圈時因為找不到變數而報錯（Warning）。
 */
$phone = isset($_GET["phone"]) ? $_GET["phone"] : []; 

/**
 * 定義手機廠牌的【關鍵字對照表】（Key-Value 對陣列）。
 * 這是業界標準寫法，用來取代傳統冗長的 switch...case。
 * 未來如果需要增加新廠牌（例如 5 是 SAMSUNG），只需在這裡加一行，不用改動下方任何程式碼。
 */
$brand_map = [
    1 => "HTC",
    2 => "APPLE",
    3 => "ASUS",
    4 => "SONY"
];

// 建立一個空的陣列，用來儲存待會比對成功、真正要顯示給使用者看的手機廠牌名稱
$selected_brands = [];

/**
 * 開始處理資料：
 * !empty($phone)：確保使用者在網址上有傳遞資料，且資料不是空的，才進入處理。
 */
if (!empty($phone)) {
    // 使用 foreach 迴圈，逐一檢查使用者勾選的每一個號碼（例如：1、3）
    foreach ($phone as $value) {
        
        /**
         * 安全性過濾：強制將接收到的網址參數轉換為【整數型態】（Integer）。
         * 這樣可以防止惡意使用者在網址列輸入奇怪的文字或駭客程式碼，確保資料安全。
         */
        $id = (int)$value; 
        
        /**
         * 檢查使用者傳過來的號碼（$id），有沒有存在於我們定義的對照表（$brand_map）中。
         * 例如：如果 $id 是 2，對照表有 2 (APPLE)，這就是有效的資料。
         */
        if (isset($brand_map[$id])) {
            // 比對成功後，把對照表中的廠牌名稱（例如 "APPLE"）塞進剛才準備好的 $selected_brands 陣列中
            $selected_brands[] = $brand_map[$id];
        }
    }
}
?>

<!DOCTYPE html>
<html lang="zh-Hant-TW">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>手機廠牌查詢結果</title>
</head>
<body>
    <div>
      <p>您使用過的手機廠牌有：</p>
      
      <?php
      // =========================================================================
      // 2. 【畫面單純輸出區】（放 body 內）
      //    核心觀念：這裡不處理複雜的邏輯，只負責將最上面大腦「算好、過濾完」的結果印出來。
      // =========================================================================
      
      /**
       * 判斷剛才在最上方處理完的 $selected_brands 陣列裡面有沒有東西。
       * !empty($selected_brands)：如果裡面有成功的廠牌名稱，就準備印出來。
       */
      if (!empty($selected_brands)) {
          
          // 使用 foreach 迴圈，把剛才存好的廠牌名稱一個一個抓出來
          foreach ($selected_brands as $brand) {
              
              /**
               * htmlspecialchars()：這是防止 XSS（跨網站指令碼）攻擊的必備安全函數。
               * 它會把敏感的 HTML 字元（如 < 或 >）轉成安全字元，確保瀏覽器單純將它當作一般文字顯示。
               * <br> 是網頁的換行標籤。
               */
              echo htmlspecialchars($brand) . "<br>";
          }
          
      } else {
          // 如果使用者完全沒勾選，或者傳過來的代碼在對照表找不到，就顯示這行提示
          echo "未選擇任何手機";
      }
      ?>
      
    </div>
</body>
</html>

